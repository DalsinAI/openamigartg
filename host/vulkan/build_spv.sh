# Compiles the compute shaders into C arrays of SPIR-V, which are kept in the
# repository so building the back end needs no shader compiler:
#   ogpu.comp    -> ogpu_vk_spv.h   (ogpu_comp_spv: the 2D commands)
#   ogpu3d.comp  -> ogpu3d_spv.h    (ogpu3d_comp_spv: the 3D range's pixels; includes ogpu3d_px.h)
#   host/vulkan/build_spv.sh [ogpu.comp | ogpu3d.comp]   (both without an argument)
# Needs glslangValidator (glslang-tools), or GLSLANG naming one: Khronos's
# glslang, from its own sources.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
GLSLANG=${GLSLANG:-glslangValidator}
one() {     # shader, header, array
    "$GLSLANG" -V --target-env vulkan1.1 --vn "$3" -o "$HERE/$2.tmp" "$HERE/$1" >/dev/null
    {
        echo "/* Generated by host/vulkan/build_spv.sh from $1: do not edit. */"
        cat "$HERE/$2.tmp"
    } > "$HERE/$2"
    rm -f "$HERE/$2.tmp"
}
case ${1:-all} in
ogpu.comp) one ogpu.comp ogpu_vk_spv.h ogpu_comp_spv ;;
ogpu3d.comp) one ogpu3d.comp ogpu3d_spv.h ogpu3d_comp_spv ;;
all) one ogpu.comp ogpu_vk_spv.h ogpu_comp_spv; one ogpu3d.comp ogpu3d_spv.h ogpu3d_comp_spv ;;
*) echo "usage: $0 [ogpu.comp | ogpu3d.comp]" >&2; exit 2 ;;
esac
